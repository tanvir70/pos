/**
 * Returns a pristine Bengali product name. If the provided nameBn contains corrupt '?' characters
 * or is empty, it attempts to resolve the official Bengali name from product code or English name.
 */
export function cleanProductNameBn(
  nameBn?: string | null,
  nameEn?: string | null,
  productCode?: string | null
): string {
  // If valid Bengali name exists without corrupt '?' question marks, use it
  if (nameBn && !nameBn.includes('?') && /[ঀ-৿]/.test(nameBn)) {
    return nameBn.trim();
  }

  // 1. Match by official Syngenta product / AGI code
  if (productCode && SYNGENTA_CODE_TO_BN[productCode]) {
    return SYNGENTA_CODE_TO_BN[productCode];
  }

  // 2. Match by English brand name
  if (nameEn) {
    const trimmedEn = nameEn.trim();
    // Direct code lookup if code in English name
    for (const [brand, bnBase] of Object.entries(SYNGENTA_BRAND_TO_BN)) {
      if (trimmedEn.toLowerCase().startsWith(brand.toLowerCase())) {
        // Extract unit size if present inside parentheses e.g. "Actara 25 WG (5 gm)"
        const match = trimmedEn.match(/\(([^)]+)\)/);
        if (match && match[1]) {
          const unit = match[1];
          if (unit.toLowerCase().includes('unit') || brand.toLowerCase().includes(unit.toLowerCase())) {
            return bnBase;
          }
          return `${bnBase} (${unit})`;
        }
        return bnBase;
      }
    }
  }

  // 3. Fallback: if nameBn has no '?', return it; otherwise fallback to English name
  if (nameBn && !nameBn.includes('?')) {
    return nameBn.trim();
  }
  return nameEn ? nameEn.trim() : '';
}
